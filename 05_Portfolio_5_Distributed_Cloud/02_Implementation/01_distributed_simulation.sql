-- IMPORTANT:
-- This demonstrates regional table partitioning and read-only access.
-- PostgreSQL partitions on this instance are NOT separate database servers.
-- This script does NOT configure physical replication.

-- 1. Create or reuse a read-only demonstration role.
-- Set the role password separately in an authorised PostgreSQL session.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_roles WHERE rolname = 'cloudmart_replica_user'
    ) THEN
        CREATE ROLE cloudmart_replica_user LOGIN;
    END IF;
END
$$;

GRANT CONNECT ON DATABASE cloudmart_db TO cloudmart_replica_user;
GRANT USAGE ON SCHEMA public TO cloudmart_replica_user;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO cloudmart_replica_user;

-- 2. Recreate the regional partitioning demonstration.
DROP TABLE IF EXISTS orders_partitioned CASCADE;

CREATE TABLE orders_partitioned (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id INT NOT NULL,
    order_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    region_id VARCHAR(10) NOT NULL,
    total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    status VARCHAR(20) NOT NULL,
    PRIMARY KEY (order_id, region_id)
) PARTITION BY LIST (region_id);

CREATE TABLE orders_shard_us
    PARTITION OF orders_partitioned FOR VALUES IN ('US-EAST');

CREATE TABLE orders_shard_eu
    PARTITION OF orders_partitioned FOR VALUES IN ('EU-WEST');

CREATE TABLE orders_shard_af
    PARTITION OF orders_partitioned FOR VALUES IN ('AF-WEST');

-- 3. Insert demonstration records.
INSERT INTO orders_partitioned
    (customer_id, region_id, total_amount, status)
VALUES
    (1, 'AF-WEST', 150.00, 'COMPLETED'),
    (2, 'US-EAST', 1299.99, 'PENDING'),
    (3, 'EU-WEST', 89.99, 'SHIPPED'),
    (4, 'AF-WEST', 249.50, 'COMPLETED');

-- 4. Verify parent-table routing and regional partition contents.
SELECT region_id, COUNT(*) AS order_count, SUM(total_amount) AS total_value
FROM orders_partitioned
GROUP BY region_id
ORDER BY region_id;

SELECT 'AF-WEST' AS partition_region, COUNT(*) AS order_count
FROM orders_shard_af
UNION ALL
SELECT 'EU-WEST', COUNT(*) FROM orders_shard_eu
UNION ALL
SELECT 'US-EAST', COUNT(*) FROM orders_shard_us
ORDER BY partition_region;

-- 5. Show the execution plan for a regional query.
EXPLAIN (COSTS OFF)
SELECT order_id, customer_id, total_amount
FROM orders_partitioned
WHERE region_id = 'AF-WEST';